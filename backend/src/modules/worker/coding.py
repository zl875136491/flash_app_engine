async def generate_code(
    *,
    requirement: str,
    plan: dict[str, Any],
    gateway: LocalModelGateway,
    mock: bool = False,
) -> dict[str, Any]:
    if mock:
        return mock_code_bundle(requirement, plan)

    user_prompt = (
        f"用户需求：\n{requirement}\n\n"
        f"架构方案 JSON：\n{plan}\n\n"
        "请生成完整可运行代码文件列表 JSON。"
    )
    text = await gateway.seedcoder.chat(
        [
            {"role": "system", "content": CODE_SYSTEM},
            {"role": "user", "content": user_prompt},
        ],
        enable_thinking=False,
        temperature=0.2,
        max_tokens=4096,
    )
    data = extract_json_object(text)
    if not isinstance(data.get("files"), list) or not data["files"]:
        raise ValueError("代码生成结果缺少 files")
    return data


def write_code_bundle(task_id: str, bundle: dict[str, Any]) -> str:
    settings = get_settings()
    root = Path(settings.generated_code_root) / task_id
    root.mkdir(parents=True, exist_ok=True)

    for item in bundle.get("files") or []:
        rel = str(item.get("path") or "").strip().lstrip("/")
        content = item.get("content")
        if not rel or content is None:
            continue
        # 防止路径穿越
        target = (root / rel).resolve()
        if not str(target).startswith(str(root.resolve())):
            raise ValueError(f"非法文件路径: {rel}")
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(str(content), encoding="utf-8")

    logger.info("code written to %s files=%s", root, len(bundle.get("files") or []))
    return str(root)
